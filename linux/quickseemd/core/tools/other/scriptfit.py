def _is_han(ch: str) -> bool:
    cp = ord(ch)
    return 0x4E00 <= cp <= 0x9FFF or 0x3400 <= cp <= 0x4DBF or 0x20000 <= cp <= 0x2FFFF


def _is_hangul(ch: str) -> bool:
    cp = ord(ch)
    return 0xAC00 <= cp <= 0xD7A3 or 0x1100 <= cp <= 0x11FF or 0x3130 <= cp <= 0x318F


def _is_kana(ch: str) -> bool:
    return 0x3040 <= ord(ch) <= 0x30FF  # 全形平假名、片假名（不含半形）


SAMPLE_CHARS = 200_000
_WESTERN_MAX_SHARE = 0.3


def plausibility(family: str, text: str) -> float:
    """0–1：text 像不像 family（"zh"、"ko"、"ja"、"latin"）的文字。"""
    sample = text[:SAMPLE_CHARS]
    wide = [c for c in sample if ord(c) > 0x7F]
    if not wide:
        return 1.0
    if family == "zh":
        han = [c for c in wide if _is_han(c)]
        return sum(c in COMMON_HANZI for c in han) / len(han) if han else 0.0
    if family == "ko":
        return sum(_is_hangul(c) for c in wide) / len(wide)
    if family == "ja":
        return sum(_is_kana(c) for c in wide) / len(wide)
    letters = sum(c.isalpha() for c in wide) / len(wide)
    # 西歐文字裡重音字母只是少數；整段幾乎都是非英文字元時多半是用錯編碼的亞洲文字
    return letters if len(wide) / max(len(sample), 1) < _WESTERN_MAX_SHARE else letters * 0.2
